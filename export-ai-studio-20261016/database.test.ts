import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { AppDatabase } from './database.ts';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'qr-db-'));
const file = path.join(dir, 'test.sqlite');
let db = new AppDatabase(file);
assert.equal(db.load(), null);
const state = { projects: [{ id: 'p1', destinationUrl: 'https://example.com', destinationHistory: [{ url: 'old' }] }], users: [{ id: 'u1' }], scans: [{ id: 's1', projectId: 'p1' }], auth: { hash: 'unchanged' } };
db.save(state);
db.setSession('token', { token: 'token', expiresAt: Date.now() + 60000 });
db.close();
db = new AppDatabase(file);
assert.deepEqual(db.load(), state);
assert.equal(db.getSessions().length, 1);
assert.throws(() => db.save({ ...state, projects: [{ id: 'duplicate' }, { id: 'duplicate' }] }));
assert.deepEqual(db.load(), state, 'failed transaction must preserve all previous records');
db.deleteSession('token');
assert.equal(db.getSessions().length, 0);
db.save({ projects: [], users: [], scans: [], auth: state.auth });
assert.deepEqual(db.load()?.projects, []);
db.close();
fs.rmSync(dir, { recursive: true });
console.log('PASS: restart persistence, transaction rollback, sessions and empty collections');
